#!/usr/bin/env node
/* global process */
/**
 * Time-zone -> country table generator (#125).
 *
 * Writes `infrastructure/lambda/registry/timeZoneCountryData.mjs`, the static IANA zone ->
 * ISO 3166-1 alpha-2 map the registry Lambda uses to stamp `deviceCountry` from the device's time
 * zone (no IP, no third party). The hand-written logic lives in `timeZoneCountry.mjs`; the data
 * module holds data only and is OVERWRITTEN WHOLESALE on every run (no in-place markers, nothing
 * hand-edited in it), so a refresh is:
 *
 *   node scripts/gen-timezone-countries.mjs
 *   git diff infrastructure/lambda/registry/timeZoneCountryData.mjs   # review, then commit
 *
 * Sources, from the system tzdata (the `tzdata` package; `/usr/share/zoneinfo`):
 *   - `zone.tab`: one country per canonical zone. This wins: a few names are both a zone.tab
 *     entry and a backward link to another country's zone (`Europe/Bratislava` is SK in zone.tab
 *     and a link to `Europe/Prague`, CZ), and the device is in the zone.tab country.
 *   - `tzdata.zi`, its `L <target> <alias>` lines (the installed form of `backward`): an old or
 *     alternate name (`Asia/Calcutta`, which V8 still reports) takes its target's country.
 *     Targets with no country (`Etc/UTC`, `Etc/GMT`) leave the alias out, so it maps to null.
 *
 * Only `Area/Location` names are emitted: single-segment legacy names (`Singapore`, `GB`) fail
 * `countryForTimeZone`'s shape check, so they would be dead entries. The output is sorted and
 * carries no timestamp, so two runs on the same tzdata are byte-identical. The header names the
 * tzdata version (the `# version` line of `tzdata.zi`) the table was built from.
 *
 * Fails loudly, naming the path, when a source file cannot be read or yields nothing.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ZONEINFO = '/usr/share/zoneinfo';
const ZONE_TAB = path.join(ZONEINFO, 'zone.tab');
const TZDATA_ZI = path.join(ZONEINFO, 'tzdata.zi');
const OUT = path.join(ROOT, 'infrastructure', 'lambda', 'registry', 'timeZoneCountryData.mjs');

const COUNTRY_RE = /^[A-Z]{2}$/;

function read(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch (err) {
    throw new Error(
      `cannot read ${file} (${err.code || err.message}); install the tzdata package and re-run`
    );
  }
}

/** `zone.tab`: `CC<TAB>coordinates<TAB>Zone[<TAB>comment]`, `#` comments. */
function parseZoneTab(text) {
  const map = new Map();
  for (const line of text.split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const [cc, , zone] = line.split('\t');
    if (!COUNTRY_RE.test(cc) || !zone) throw new Error(`${ZONE_TAB}: unexpected line: ${line}`);
    map.set(zone.trim(), cc);
  }
  if (!map.size) throw new Error(`${ZONE_TAB}: no zones found`);
  return map;
}

/** `tzdata.zi`: the `# version <v>` header and every `L <target> <alias>` link line. */
function parseTzdataZi(text) {
  const version = /^# version (\S+)$/m.exec(text)?.[1];
  if (!version) throw new Error(`${TZDATA_ZI}: no "# version" line`);
  const links = [];
  for (const line of text.split('\n')) {
    if (!line.startsWith('L ')) continue;
    const [, target, alias] = line.trim().split(/\s+/);
    if (!target || !alias) throw new Error(`${TZDATA_ZI}: unexpected link line: ${line}`);
    links.push({ target, alias });
  }
  if (!links.length) throw new Error(`${TZDATA_ZI}: no link (L) lines found`);
  return { version, links };
}

function build() {
  const zones = parseZoneTab(read(ZONE_TAB));
  const { version, links } = parseTzdataZi(read(TZDATA_ZI));

  const table = new Map(zones);
  for (const { target, alias } of links) {
    // zone.tab wins over a link (see the header); a link to a country-less zone adds nothing.
    if (table.has(alias) || !zones.has(target)) continue;
    table.set(alias, zones.get(target));
  }

  const entries = [...table]
    .filter(([zone]) => zone.includes('/'))
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

  const body = entries.map(([zone, cc]) => `  '${zone}': '${cc}',`).join('\n');
  const source =
    `// GENERATED by scripts/gen-timezone-countries.mjs from IANA tzdata ${version}\n` +
    `// (zone.tab + tzdata.zi links). Do not edit by hand: re-run the generator and review the diff.\n` +
    `\n` +
    `/** IANA time zone -> ISO 3166-1 alpha-2 country. Read through \`countryForTimeZone\`. */\n` +
    `export const ZONE_COUNTRIES = Object.freeze({\n${body}\n});\n`;

  writeFileSync(OUT, source);
  process.stdout.write(
    `wrote ${path.relative(ROOT, OUT)}: ${entries.length} zones from tzdata ${version}\n`
  );
}

try {
  build();
} catch (err) {
  process.stderr.write(`[gen-timezone-countries] FAILED: ${err.message}\n`);
  process.exit(1);
}
