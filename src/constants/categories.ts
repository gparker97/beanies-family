/** The picture for a category or group with none of its own (a legacy or custom id). */
export const FALLBACK_CATEGORY_EMOJI = '📦';

/** A category's picture, or the fallback box for an id the map does not know. */
export function categoryEmoji(id: string): string {
  return CATEGORY_EMOJI_MAP[id] || FALLBACK_CATEGORY_EMOJI;
}

export function getCategoryById(id: string): Category | undefined {
  return ALL_CATEGORIES.find((cat) => cat.id === id);
}

export function getCategoriesByType(type: 'income' | 'expense'): CategoryDef[] {
  return type === 'income' ? INCOME_CATEGORIES : EXPENSE_CATEGORIES;
}

// Group categories by their group property
export interface CategoryGroup {
  name: string;
  categories: CategoryDef[];
}

export function getCategoriesGrouped(type: 'income' | 'expense'): CategoryGroup[] {
  const categories = getCategoriesByType(type);
  const groupMap = new Map<string, CategoryDef[]>();

  for (const cat of categories) {
    const groupName = cat.group || 'Other';
    const existing = groupMap.get(groupName) || [];
    existing.push(cat);
    groupMap.set(groupName, existing);
  }

  // Convert to array, sort categories within groups (Other * last), sort groups (Other last)
  const groups: CategoryGroup[] = [];
  for (const [name, cats] of groupMap.entries()) {
    groups.push({
      name,
      categories: cats.sort((a, b) => {
        const aIsOther = a.name.toLowerCase().startsWith('other');
        const bIsOther = b.name.toLowerCase().startsWith('other');
        if (aIsOther !== bIsOther) return aIsOther ? 1 : -1;
        return a.name.localeCompare(b.name);
      }),
    });
  }

  return groups.sort((a, b) => {
    if (a.name === 'Other') return 1;
    if (b.name === 'Other') return -1;
    return a.name.localeCompare(b.name);
  });
}

/**
 * Map legacy category IDs (removed in the Mar 15 2026 category overhaul)
 * to their current equivalents so old transactions and recurring items
 * still match budget lookups.
 */
const LEGACY_CATEGORY_MAP: Record<string, string> = {
  subscriptions: 'other_subscriptions',
  education: 'other_education',
};

/** Normalize a category ID, mapping removed legacy IDs to current equivalents. */
export function normalizeCategoryId(categoryId: string): string {
  return LEGACY_CATEGORY_MAP[categoryId] ?? categoryId;
}

/** Get the list of category IDs belonging to a given expense group name */
export function getCategoryIdsForGroup(groupName: string): string[] {
  return EXPENSE_CATEGORIES.filter((c) => c.group === groupName).map((c) => c.id);
}

/** Budget group-level helpers */
const GROUP_PREFIX = 'group:';

export function isGroupBudget(categoryId: string): boolean {
  return categoryId.startsWith(GROUP_PREFIX);
}

export function getGroupName(categoryId: string): string {
  return categoryId.slice(GROUP_PREFIX.length);
}

export function makeGroupBudgetId(groupName: string): string {
  return `${GROUP_PREFIX}${groupName}`;
}

