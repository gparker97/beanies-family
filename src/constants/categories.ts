import type { Category } from '@/types/models';

/**
 * A transaction category's definition: the display shape (`Category`, the model type, which
 * stays display-only) plus the words that name it.
 */
export interface CategoryDef extends Category {
  /**
   * Words (English and Simplified Chinese, lowercase) that name this category in a
   * description: the category guess (`utils/categorySuggest.ts`) and the picker's search read
   * them through the one matcher (`utils/keywordSuggest.ts`). Never shown. Conservative: a
   * wrong guess lands in the wrong budget line. Empty only for a catch-all
   * (`TRANSACTION_CATCH_ALL_IDS`).
   */
  keywords: readonly string[];
  /** Generic words: any keyword of any category in the same table beats them. */
  weakKeywords?: readonly string[];
}

